#!/usr/bin/env bash
# easy-novnc: Ubuntu/Debian + systemd or container, run as root.
set -Eeuo pipefail
umask 077
export LC_ALL=C

APP=/opt/easy-novnc
STATE=/var/lib/easy-novnc
CONF=/etc/easy-novnc/config
SERVICE=easy-novnc.service
PORT_ARG= DISPLAY_ARG= GEOMETRY_ARG= PASSWORD_FILE=
RESET_PASSWORD=0
SAVED_CONFIG=0

usage() {
    cat <<'HELP'
Usage: sudo bash install-vnc.sh [options]

  --port N              Browser port (default: first free port in 6080..6099)
  --display N           X display 1..99 (default: choose a free display)
  --geometry WxH        Desktop resolution (default: 1280x960)
  --password-file FILE  Read a VNC password from a private file
  --reset-password      Replace the saved VNC password
  -h, --help            Show this help

First run prompts for a password: 6..8 printable ASCII characters.
Reruns reuse the saved password, display, port and resolution unless overridden.
Only expose the browser port. VNC itself is bound to localhost.
Public HTTP is NOT encrypted. Prefer an SSH tunnel or HTTPS + WebSocket proxy.
This script creates a dedicated desktop; it never kills unrelated VNC sessions.
HELP
}
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
step() { printf '\n== %s ==\n' "$*"; }
trap 'printf "\nFAILED at line %s. Fix the error above and rerun.\n" "$LINENO" >&2' ERR

while (($#)); do
    case "$1" in
        --port|--display|--geometry|--password-file)
            (($# >= 2)) || fail "Missing value for $1"
            [[ -n "$2" ]] || fail "Empty value for $1"
            case "$1" in
                --port) PORT_ARG=$2 ;;
                --display) DISPLAY_ARG=$2 ;;
                --geometry) GEOMETRY_ARG=$2 ;;
                --password-file) PASSWORD_FILE=$2 ;;
            esac
            shift 2 ;;
        --reset-password) RESET_PASSWORD=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) fail "Unknown option: $1 (see --help)" ;;
    esac
done

validate_port() {
    [[ "$1" =~ ^[1-9][0-9]{0,4}$ ]] && (( $1 >= 1024 && $1 <= 65535 )) ||
        fail 'Browser port must be an integer from 1024 to 65535.'
    [[ "$1" != 8080 ]] || fail 'Port 8080 is reserved on the target hosting platform; choose another port.'
}
validate_display() {
    [[ "$1" =~ ^[1-9][0-9]?$ ]] || fail 'Display must be an integer from 1 to 99.'
}
validate_geometry() {
    [[ "$1" =~ ^([1-9][0-9]{2,3})x([1-9][0-9]{2,3})$ ]] || fail 'Resolution must look like 1280x960.'
    (( ${BASH_REMATCH[1]} >= 640 && ${BASH_REMATCH[1]} <= 7680 &&
       ${BASH_REMATCH[2]} >= 480 && ${BASH_REMATCH[2]} <= 4320 )) ||
        fail 'Resolution must be between 640x480 and 7680x4320.'
}
[[ -z "$PORT_ARG" ]] || validate_port "$PORT_ARG"
[[ -z "$DISPLAY_ARG" ]] || validate_display "$DISPLAY_ARG"
[[ -z "$GEOMETRY_ARG" ]] || validate_geometry "$GEOMETRY_ARG"
[[ "$EUID" -eq 0 ]] || fail 'Run with sudo bash install-vnc.sh, or as root.'
[[ -r /etc/os-release ]] || fail 'Cannot identify the operating system.'
# shellcheck disable=SC1091
. /etc/os-release
[[ "${ID:-}" == ubuntu || "${ID:-}" == debian ]] || fail 'Only Ubuntu and Debian are supported.'
command -v apt-get >/dev/null || fail 'apt-get is required.'
command -v flock >/dev/null || fail 'flock is required (install util-linux first).'
exec 8>/run/easy-novnc-install.lock
flock -n 8 || fail 'Another installation is running.'

PORT=6080
DISPLAY_NUM=
GEOMETRY=1280x960
if [[ -e "$CONF" ]]; then
    SAVED_CONFIG=1
    [[ -f "$CONF" && ! -L "$CONF" && "$(stat -c %u "$CONF")" == 0 ]] || fail "Unsafe config: $CONF"
    # This is a root-owned file generated by this installer.
    # shellcheck disable=SC1090
    . "$CONF"
fi
PORT=${PORT_ARG:-$PORT}
DISPLAY_NUM=${DISPLAY_ARG:-$DISPLAY_NUM}
GEOMETRY=${GEOMETRY_ARG:-$GEOMETRY}
validate_port "$PORT"
validate_geometry "$GEOMETRY"
[[ -z "$DISPLAY_NUM" ]] || validate_display "$DISPLAY_NUM"
if [[ -n "$DISPLAY_NUM" ]]; then
    (( PORT != 5900 + DISPLAY_NUM )) || fail 'Browser port must differ from the VNC port.'
fi

# Read secrets before installing anything. Never put a password on a command line.
NEW_PASSWORD=0
VNC_PASSWORD=
if [[ -n "$PASSWORD_FILE" || "$RESET_PASSWORD" == 1 || ! -s "$STATE/passwd" ]]; then
    NEW_PASSWORD=1
    if [[ -n "$PASSWORD_FILE" ]]; then
        [[ -f "$PASSWORD_FILE" && -r "$PASSWORD_FILE" ]] || fail 'Password file is not readable.'
        VNC_PASSWORD=$(< "$PASSWORD_FILE")
    else
        [[ -t 0 ]] || fail 'No saved password. Use an interactive terminal or --password-file FILE.'
        printf 'VNC password (6-8 printable ASCII characters): ' >&2
        IFS= read -rs VNC_PASSWORD; printf '\n' >&2
        printf 'Repeat VNC password: ' >&2
        IFS= read -rs PASSWORD_CONFIRM; printf '\n' >&2
        [[ "$VNC_PASSWORD" == "$PASSWORD_CONFIRM" ]] || fail 'Passwords do not match.'
        unset PASSWORD_CONFIRM
    fi
    [[ ${#VNC_PASSWORD} -ge 6 && ${#VNC_PASSWORD} -le 8 && "$VNC_PASSWORD" != *$'\n'* ]] ||
        fail 'VNC authentication supports only 6-8 characters here; longer passwords would be truncated.'
    printf '%s\n' "$VNC_PASSWORD" | grep -q '^[ -~]\{6,8\}$' || fail 'Use printable ASCII characters only.'
fi

step '1/4 Installing desktop, TigerVNC and noVNC'
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends \
    xfce4 xfce4-terminal dbus-x11 dbus-daemon \
    tigervnc-standalone-server tigervnc-tools novnc websockify \
    xauth x11-utils x11-xserver-utils fonts-dejavu-core python3 util-linux
[[ -f /usr/share/novnc/vnc.html ]] || fail 'noVNC vnc.html is missing.'
for tool in Xtigervnc tigervncpasswd websockify dbus-run-session xfce4-session xdpyinfo setsid; do
    command -v "$tool" >/dev/null || fail "Required command missing: $tool"
done

# Refuse to overwrite an unrelated runner or service.
if [[ -e "$APP/run.sh" ]]; then
    grep -q '^# easy-novnc-managed-runner$' "$APP/run.sh" || fail "$APP/run.sh already exists and is not ours."
fi
if [[ -e /etc/systemd/system/$SERVICE ]]; then
    grep -q '^# easy-novnc-managed-service$' "/etc/systemd/system/$SERVICE" || fail 'An unrelated systemd service uses our name.'
fi
USE_SYSTEMD=0
if command -v systemctl >/dev/null && [[ -d /run/systemd/system ]] &&
    [[ "$(< /proc/1/comm)" == systemd ]]; then
    USE_SYSTEMD=1
fi

step '2/4 Preparing a private VNC session'
# Stop only our own service. Other VNC desktops are left untouched.
if (( USE_SYSTEMD )) && [[ -f /etc/systemd/system/$SERVICE ]]; then
    systemctl stop "$SERVICE"
fi
if [[ -f "$APP/run.sh" ]]; then
    bash "$APP/run.sh" stop
fi

port_free() {
    python3 - "$1" <<'PY'
import socket, sys
with socket.socket() as sock:
    try:
        sock.bind(('0.0.0.0', int(sys.argv[1])))
    except OSError:
        sys.exit(1)
PY
}
if [[ -z "$PORT_ARG" && "$SAVED_CONFIG" == 0 ]]; then
    FOUND_PORT=0
    for candidate in {6080..6099}; do
        if [[ -n "$DISPLAY_NUM" ]] && (( candidate == 5900 + DISPLAY_NUM )); then continue; fi
        if port_free "$candidate"; then PORT=$candidate; FOUND_PORT=1; break; fi
    done
    (( FOUND_PORT )) || fail 'No free browser port from 6080 to 6099. Choose --port N.'
fi
port_free "$PORT" || fail "Port $PORT is occupied. Rerun with --port N using a free port."
display_free() {
    [[ ! -e "/tmp/.X${1}-lock" && ! -e "/tmp/.X11-unix/X${1}" ]] &&
        (( PORT != 5900 + $1 )) && port_free "$((5900 + $1))"
}
if [[ -z "$DISPLAY_NUM" ]]; then
    for candidate in {1..99}; do
        if display_free "$candidate"; then DISPLAY_NUM=$candidate; break; fi
    done
    [[ -n "$DISPLAY_NUM" ]] || fail 'No free X display found.'
else
    display_free "$DISPLAY_NUM" || fail "Display :$DISPLAY_NUM or its VNC port is in use. Choose --display N; no existing session was killed."
fi
install -d -m 700 "$APP" "$STATE" /etc/easy-novnc /var/log/easy-novnc
if (( NEW_PASSWORD )); then
    PASSWORD_TMP=$(mktemp "$STATE/passwd.XXXXXX")
    if ! printf '%s\n' "$VNC_PASSWORD" | tigervncpasswd -f >"$PASSWORD_TMP"; then
        rm -f -- "$PASSWORD_TMP"
        fail 'Could not create the VNC password file.'
    fi
    chmod 600 "$PASSWORD_TMP"
    mv -f -- "$PASSWORD_TMP" "$STATE/passwd"
fi
unset VNC_PASSWORD
{
    printf 'PORT=%q\n' "$PORT"
    printf 'DISPLAY_NUM=%q\n' "$DISPLAY_NUM"
    printf 'GEOMETRY=%q\n' "$GEOMETRY"
} >"$CONF"
chmod 600 "$CONF"

cat >"$APP/run.sh" <<'RUNNER'
#!/usr/bin/env bash
# easy-novnc-managed-runner
set -Eeuo pipefail
umask 077
SELF=/opt/easy-novnc/run.sh
PIDFILE=/run/easy-novnc/pid

if [[ "${1:-start}" == stop || "${1:-start}" == status ]]; then
    python3 - "$SELF" "$PIDFILE" "$1" <<'PY'
import os, signal, sys, time
runner, pidfile, action = sys.argv[1:]
def identity():
    try:
        pid_text, started = open(pidfile).read().split()
        pid = int(pid_text)
        if pid <= 1: return None
        args = open(f'/proc/{pid}/cmdline', 'rb').read().split(b'\0')
        # starttime is field 22; comm (field 2) can contain spaces.
        fields = open(f'/proc/{pid}/stat').read().rsplit(')', 1)[1].split()
        if os.fsencode(runner) in args and fields[19] == started:
            return pid
    except (OSError, ValueError, IndexError):
        pass
    return None
pid = identity()
if action == 'status':
    print('RUNNING' if pid else 'STOPPED')
    sys.exit(0 if pid else 1)
if pid:
    os.kill(pid, signal.SIGTERM)
    for _ in range(100):
        if identity() != pid: break
        time.sleep(0.1)
    else:
        sys.exit('Managed process did not stop within 10 seconds; inspect before retrying.')
PY
    exit $?
fi
[[ "${1:-start}" == start ]] || { printf 'Usage: %s [start|stop|status]\n' "$SELF" >&2; exit 2; }
# shellcheck disable=SC1091
. /etc/easy-novnc/config
install -d -m 700 /run/easy-novnc /run/easy-novnc/xdg
exec 9>/run/easy-novnc/lock
flock -n 9 || { printf 'Already running.\n' >&2; exit 1; }
python3 - "$$" >"$PIDFILE" <<'PY'
import sys
pid = sys.argv[1]
fields = open(f'/proc/{pid}/stat').read().rsplit(')', 1)[1].split()
print(pid, fields[19])
PY
pids=()
cleanup() {
    trap - EXIT TERM INT
    for pid in "${pids[@]}"; do kill -TERM -- "-$pid" 2>/dev/null || true; done
    # Give each process group time to close its display and sockets.
    for _ in {1..30}; do
        alive=0
        for pid in "${pids[@]}"; do
            if kill -0 -- "-$pid" 2>/dev/null; then alive=1; fi
        done
        (( alive )) || break
        sleep 0.1
    done
    for pid in "${pids[@]}"; do kill -KILL -- "-$pid" 2>/dev/null || true; done
    wait 2>/dev/null || true
    rm -f "$PIDFILE"
}
trap cleanup EXIT
trap 'exit 0' TERM INT
export HOME=/root USER=root LOGNAME=root
export DISPLAY=":$DISPLAY_NUM"
export XAUTHORITY=/var/lib/easy-novnc/Xauthority
export XDG_RUNTIME_DIR=/run/easy-novnc/xdg
unset SESSION_MANAGER DBUS_SESSION_BUS_ADDRESS
cd /root
# Private X authentication; do not use xhost + or disable access control.
: >"$XAUTHORITY"
cookie=$(python3 -c 'import secrets; print(secrets.token_hex(16))')
xauth -f "$XAUTHORITY" add "$DISPLAY" MIT-MAGIC-COOKIE-1 "$cookie"
unset cookie
setsid Xtigervnc "$DISPLAY" \
    -geometry "$GEOMETRY" -depth 24 \
    -rfbport "$((5900 + DISPLAY_NUM))" -localhost yes \
    -SecurityTypes VncAuth -PasswordFile /var/lib/easy-novnc/passwd \
    -auth "$XAUTHORITY" -nolisten tcp -AlwaysShared \
    >>/var/log/easy-novnc/vnc.log 2>&1 9>&- &
vnc_pid=$!; pids+=("$vnc_pid")
ready=0
for _ in {1..60}; do
    kill -0 "$vnc_pid" 2>/dev/null || { printf 'VNC exited; see vnc.log.\n' >&2; exit 1; }
    if xdpyinfo >/dev/null 2>&1; then ready=1; break; fi
    sleep 0.5
done
(( ready )) || { printf 'Timed out waiting for X.\n' >&2; exit 1; }
setsid dbus-run-session -- xfce4-session >>/var/log/easy-novnc/desktop.log 2>&1 9>&- &
desktop_pid=$!; pids+=("$desktop_pid")
setsid websockify --web=/usr/share/novnc "0.0.0.0:$PORT" "127.0.0.1:$((5900 + DISPLAY_NUM))" \
    >>/var/log/easy-novnc/web.log 2>&1 9>&- &
web_pid=$!; pids+=("$web_pid")
# A broken desktop must not leave a misleading, apparently healthy web endpoint.
rc=0
wait -n "$vnc_pid" "$desktop_pid" "$web_pid" || rc=$?
(( rc != 0 )) || rc=1
printf 'A component exited; stopping this managed session (exit %s).\n' "$rc" >&2
exit "$rc"
RUNNER
chmod 700 "$APP/run.sh"

step '3/4 Starting the managed desktop'
if (( USE_SYSTEMD )); then
    cat >"/etc/systemd/system/$SERVICE" <<'UNIT'
# easy-novnc-managed-service
[Unit]
Description=Private TigerVNC desktop with noVNC browser access
After=network.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
User=root
ExecStart=/bin/bash /opt/easy-novnc/run.sh start
Restart=on-failure
RestartSec=5
TimeoutStopSec=15
KillMode=control-group
UMask=0077
StandardOutput=append:/var/log/easy-novnc/service.log
StandardError=append:/var/log/easy-novnc/service.log

[Install]
WantedBy=multi-user.target
UNIT
    chmod 644 "/etc/systemd/system/$SERVICE"
    systemctl daemon-reload
    systemctl enable --now "$SERVICE"
else
    # Close the installer lock in the child; otherwise future installs would block.
    nohup /bin/bash "$APP/run.sh" start >>/var/log/easy-novnc/service.log 2>&1 </dev/null 8>&- &
fi

step '4/4 Verifying HTTP and WebSocket-to-VNC forwarding'
python3 - "$PORT" <<'PY'
import base64, os, socket, sys, time, urllib.request
port = int(sys.argv[1])
# Ignore proxy environment variables for the loopback health check.
http = urllib.request.build_opener(urllib.request.ProxyHandler({}))
last = None
for _ in range(45):
    try:
        with http.open(f'http://127.0.0.1:{port}/vnc.html', timeout=2) as response:
            if response.status != 200 or b'noVNC' not in response.read():
                raise RuntimeError('Unexpected page response')
        with socket.create_connection(('127.0.0.1', port), timeout=3) as sock:
            key = base64.b64encode(os.urandom(16)).decode()
            request = (
                'GET /websockify HTTP/1.1\r\n'
                f'Host: 127.0.0.1:{port}\r\n'
                'Upgrade: websocket\r\nConnection: Upgrade\r\n'
                f'Sec-WebSocket-Key: {key}\r\n'
                'Sec-WebSocket-Version: 13\r\nSec-WebSocket-Protocol: binary\r\n\r\n'
            )
            sock.sendall(request.encode())
            data = b''
            while b'\r\n\r\n' not in data:
                chunk = sock.recv(4096)
                if not chunk or len(data) > 16384: raise RuntimeError('Invalid WebSocket response')
                data += chunk
            headers, data = data.split(b'\r\n\r\n', 1)
            if b' 101 ' not in headers.split(b'\r\n')[0]:
                raise RuntimeError('WebSocket upgrade failed')
            while b'RFB ' not in data:
                chunk = sock.recv(4096)
                if not chunk or len(data) > 4096: raise RuntimeError('No VNC protocol greeting')
                data += chunk
        print('PASS: noVNC HTTP 200, WebSocket 101, VNC greeting received.')
        break
    except (OSError, RuntimeError) as exc:
        last = exc
        time.sleep(1)
else:
    sys.exit(f'Health check failed: {last}. See /var/log/easy-novnc/*.log')
PY
bash "$APP/run.sh" status
printf '\nREADY\nExpose only this browser port: %s\n' "$PORT"
printf 'Open: http://<platform-provided-host-and-port>/vnc.html\n'
printf 'Use the VNC password, not your SSH password.\n'
printf 'Internal VNC: localhost:%s | display :%s | resolution %s\n' "$((5900 + DISPLAY_NUM))" "$DISPLAY_NUM" "$GEOMETRY"
printf 'Logs: /var/log/easy-novnc/\n'
if (( USE_SYSTEMD )); then
    printf 'Boot startup: enabled. Restart: systemctl restart %s\n' "$SERVICE"
else
    printf 'Container mode: survives SSH disconnect, NOT container restart.\n'
    printf 'For container boot, append the manual-start command to your platform startup script.\n'
    printf 'Do not replace the existing image startup commands.\n'
    printf 'Manual start: nohup /bin/bash /opt/easy-novnc/run.sh start >>/var/log/easy-novnc/service.log 2>&1 </dev/null &\n'
fi
printf '\nSECURITY: This desktop runs as root. VNC passwords are limited to 8 characters.\n'
printf 'Public HTTP is unencrypted. Prefer an SSH tunnel or HTTPS with WebSocket support.\n'
printf 'Do not expose the internal VNC or X11 ports. No firewall/platform rules were changed.\n'
